import assert from 'node:assert/strict';
import {validateZaraRequest,createCharacterProvider} from './adapter.mjs';
assert.equal(validateZaraRequest({message:' Salam ',mode:'flirty'}).mode,'adult');
assert.equal(validateZaraRequest({message:'Salam'}).language,'Roman Urdu');
assert.throws(()=>validateZaraRequest({message:' '}));
assert.equal((await createCharacterProvider().reply({message:'hello'})).code,'CHARACTERAI_DISABLED');
assert.equal((await createCharacterProvider({enabled:true}).reply({message:'hello'})).code,'CHARACTERAI_UNAVAILABLE');
assert.equal((await createCharacterProvider({enabled:true,send:async()=>({reply:' Walaikum salam '})}).reply({message:'Salam'})).reply,'Walaikum salam');
assert.equal((await createCharacterProvider({enabled:true,send:async()=>({reply:''})}).reply({message:'Salam'})).code,'CHARACTERAI_EMPTY');
assert.equal((await createCharacterProvider({enabled:true,send:async()=>{throw Error('private secret')}}).reply({message:'Salam'})).code,'CHARACTERAI_ERROR');
assert.equal((await createCharacterProvider({enabled:true,send:async()=>({reply:'ok'})}).reply({message:''})).code,'CHARACTERAI_BAD_REQUEST');
const timeout=await createCharacterProvider({enabled:true,timeoutMs:100,send:async(_input,{signal})=>new Promise((_,reject)=>{signal.addEventListener('abort',()=>reject(new Error('aborted')),{once:true})})}).reply({message:'Salam'});
assert.equal(timeout.code,'CHARACTERAI_TIMEOUT');
console.log('PASS: 10 isolated adapter checks');
